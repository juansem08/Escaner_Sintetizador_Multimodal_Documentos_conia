export type AppLanguage = 'es' | 'en';

export const STRINGS: Record<AppLanguage, Record<StringKey, string>> = { es, en };

export type TFunction = (key: StringKey, params?: Record<string, string | number>) => string;

export function makeT(lang: AppLanguage): TFunction {
  const dict = STRINGS[lang];
  return (key, params) =>
    (dict[key] ?? es[key] ?? key).replace(/\{(\w+)\}/g, (_, name: string) => String(params?.[name] ?? ''));
}

